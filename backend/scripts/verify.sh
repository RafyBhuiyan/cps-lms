# The scope is resolved server-side and injected as a documentId allowlist; see
# scopeQueryToDocuments. student2 and instructor2 own nothing here.
#
# One progress document exists per lesson — normalize_progress touches all five,
# completing three of them — so the owner's document count is the lesson count,
# not the completed count.
#
# Two guarantees here, so two kinds of assertion. A student's scope is *exactly*
# their own rows, which is an equality. A manager's scope is a superset — the
# course's instructor sees their students' rows, a content_manager and an admin
# see everyone's — so counting rows there only holds while the seeded student is
# the only person in the database. Against production they were not: one real
# signup enrolling in the seeded course turned "enrollments — owning instructor"
# into got=2 want=1, a failure that says nothing about scoping. Containment is
# the property that actually matters, and it survives other people using the app.

# How many of $owned the token can see. Equal to the total when the manager's
# scope covers the owner, lower when rows are being hidden from someone who
# should see them.
seen_all_of() {
  local path=$1 token=$2 owned=$3 seen id n=0
  seen=$(ids "/api/$path?pagination[pageSize]=100" "$token")
  for id in $owned; do
    if printf '%s\n' "$seen" | grep -qxF "$id"; then n=$((n + 1)); fi
  done
  echo "$n"
}

