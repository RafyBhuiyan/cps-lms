  check "$path — owning student" "$own" "$(printf '%s\n' "$owned" | grep -c . || true)"
  check "$path — other student" 0 "$(rows "/api/$path?pagination[pageSize]=100" "$T_S2")"
  check "$path — owning instructor" "$own" "$(seen_all_of "$path" "$T_I1" "$owned")"
