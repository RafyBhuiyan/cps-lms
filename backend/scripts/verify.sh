#!/usr/bin/env bash
#
# End-to-end verification of the quiz and progress systems — `npm run verify`
# from the backend directory, against a running server with `npm run seed` data.
#
# Every line asserts an expected HTTP status or row count. A FAIL is a real
# defect. Written as a shell script rather than with a test runner because the
# backend has no test dependency installed and these assertions are about HTTP
# responses, not units.
#
# Repeatable: it normalizes the progress state before asserting on it, so it does
# not depend on what a previous run left behind.

set -u

API=${API:-http://localhost:1337}
PASSWORD=Demo1234!
COURSE_SLUG=intro-to-typescript
# The post that has to be unpublished for the visibility assertions to mean
# anything. Looked up by slug for the same reason the course is: documentIds are
# regenerated by every fresh seed.
DRAFT_BLOG_SLUG=unpublished-draft-post

pass=0
fail=0

# --------------------------------------------------------------------------- #
# Helpers                                                                     #
# --------------------------------------------------------------------------- #

# All curl calls pass -g. Without it curl treats the `[` in `filters[x]` as URL
# globbing and never sends the request, which reads as "zero rows" — a silent
# false pass.
CURL="curl -s -g"

check() {
  if [ "$2" = "$3" ]; then
    printf '  PASS  %-56s %s\n' "$1" "$3"
    pass=$((pass + 1))
  else
    printf '  FAIL  %-56s got=%s want=%s\n' "$1" "$3" "$2"
    fail=$((fail + 1))
  fi
}

# status <method> <path> [token] [json-body]
status() {
  local m=$1 p=$2 t=${3:-} b=${4:-}
  if [ -n "$b" ]; then
    $CURL -o /dev/null -w '%{http_code}' -X "$m" "$API$p" \
      ${t:+-H "Authorization: Bearer $t"} -H 'Content-Type: application/json' -d "$b"
  else
    $CURL -o /dev/null -w '%{http_code}' -X "$m" "$API$p" ${t:+-H "Authorization: Bearer $t"}
  fi
}

get() { $CURL "$API$1" ${2:+-H "Authorization: Bearer $2"}; }

post() {
  $CURL -X POST "$API$1" ${2:+-H "Authorization: Bearer $2"} \
    -H 'Content-Type: application/json' -d "$3"
}

# The PUT twin of `post`, for the handlers whose *body* is asserted rather than
# their status — role assignment and the final-quiz link both report what they
# actually stored, and reading that back is the only way to tell a write that
# landed from one that was accepted and dropped.
put() {
  $CURL -X PUT "$API$1" ${2:+-H "Authorization: Bearer $2"} \
    -H 'Content-Type: application/json' -d "$3"
}

# Counts distinct documentIds in a response. `grep -c` counts matching *lines*
# and the body is a single line, so it would report 1 for any non-empty response.
rows() { get "$1" "${2:-}" | grep -oP '"documentId":"\K[^"]+' | sort -u | wc -l; }

# documentIds in response order.
ids() { get "$1" "${2:-}" | grep -oP '"documentId":"\K[^"]+'; }

# num <json-key> — reads a number out of the last response piped in.
num() { grep -oP "\"$1\":\"?\K[0-9.]+"; }

# --------------------------------------------------------------------------- #
# Tokens                                                                      #
# --------------------------------------------------------------------------- #
#
# `/api/auth/local` is rate-limited by users-permissions (5 attempts per
# identifier per 5 minutes). Re-running this script exhausted it, and a login
# that returns no token makes an authorized request look like a denied one — an
# anonymous PUT is 403, exactly like a forbidden one. So tokens are cached
# between runs; they are valid for 30 days.
#
# Keyed by API host, because a JWT is only meaningful to the instance that signed
# it: production and local use different JWT_SECRETs, so one shared cache file
# means every switch between environments discards six still-valid tokens and
# logs in again.
CACHE=${TOKEN_CACHE:-/tmp/lms-verify-tokens.$(printf '%s' "$API" |
  sed -e 's#^https\?://##' -e 's#[^A-Za-z0-9._-]#-#g').env}
touch "$CACHE"

# The email a token authenticates as — identity, not mere validity. A cached
# token that authenticates as the *wrong* user is far worse than no token: a
# cache in which T_I2 held the admin's JWT turned "another instructor cannot
# delete this course" into an admin deleting it, and the seed course was gone,
# with its lessons and quizzes left orphaned. Checking only for HTTP 200 does
# not catch that; checking who answered does.
token_email() {
  [ -n "${1:-}" ] || return 0
  $CURL -H "Authorization: Bearer $1" "$API/api/users/me" | grep -oP '"email":"\K[^"]+'
}

# The numeric id behind a token. Needed because two assertions below have to name
# a user in a query string or a payload, and numeric ids are no more portable
# between environments than documentIds are — see the note where this is called.
token_user_id() {
  [ -n "${1:-}" ] || return 0
  $CURL -H "Authorization: Bearer $1" "$API/api/users/me" | grep -oP '"id":\K[0-9]+' | head -1
}

ensure_token() {
  local var=$1 email=$2 cached token code attempt body who
  cached=$(grep -oP "^$var=\K.*" "$CACHE" | tail -1 || true)

  if [ "$(token_email "${cached:-}")" = "$email" ]; then
    export "$var=$cached"
    return 0
  fi

  for attempt in 1 2 3; do
    # A per-account response file, removed first. Sharing one path meant that if a
    # login did not overwrite it the next read picked up the *previous* account's
    # response — which is how a cache ended up holding the admin's JWT under all
    # six names.
    body=/tmp/lms-verify-login.$var.json
    rm -f "$body"

    code=$($CURL -o "$body" -w '%{http_code}' -X POST "$API/api/auth/local" \
      -H 'Content-Type: application/json' \
      -d "{\"identifier\":\"$email\",\"password\":\"$PASSWORD\"}")
    token=$(grep -oP '"jwt":"\K[^"]+' "$body" 2>/dev/null || true)
    who=$(grep -oP '"email":"\K[^"]+' "$body" 2>/dev/null | head -1 || true)

    # The token is cached only if the same response also identifies the account it
    # was asked for, so a token can never be filed under the wrong name.
    if [ -n "$token" ] && [ "$who" = "$email" ]; then
      grep -v "^$var=" "$CACHE" > "$CACHE.tmp" 2>/dev/null || true
      mv "$CACHE.tmp" "$CACHE"
      printf '%s=%s\n' "$var" "$token" >> "$CACHE"
      export "$var=$token"
      return 0
    fi

    echo "  login $email -> HTTP $code (as '${who:-nobody}'); waiting out the rate limit ($attempt/3)" >&2
    sleep 65
  done

  echo "LOGIN FAILED: $email (HTTP $code)" >&2
  return 1
}

# A second student and a second instructor exist only to prove that role alone
# does not grant access to another person's data or another instructor's course.
register_if_missing() {
  $CURL -o /dev/null -X POST "$API/api/auth/local/register" -H 'Content-Type: application/json' \
    -d "{\"username\":\"$1\",\"email\":\"$2\",\"password\":\"$PASSWORD\"}"
}

register_if_missing student2 student2@demo.test
register_if_missing instructor2 instructor2@demo.test

ensure_token T_S1 student@demo.test || exit 1
ensure_token T_S2 student2@demo.test || exit 1
ensure_token T_I1 instructor@demo.test || exit 1
ensure_token T_I2 instructor2@demo.test || exit 1
ensure_token T_CM cm@demo.test || exit 1
ensure_token T_ADMIN admin@demo.test || exit 1

# Then prove, before a single assertion runs, that every token authenticates as
# the person it is named for. Two failure modes this closes:
#
#   * A token that authenticates as nobody makes the whole suite fall through to
#     anonymous requests, and anonymous results look like passes — a request with
#     no token is 403 on a protected route, exactly like a denied one.
#   * A token that authenticates as the *wrong* person turns the negative checks
#     into privileged operations. The DELETE and PUT assertions below expect 403;
#     run with an over-privileged token they succeed, and this suite stops
#     verifying the system and starts damaging it.
for account in "T_S1:student@demo.test" "T_S2:student2@demo.test" \
               "T_I1:instructor@demo.test" "T_I2:instructor2@demo.test" \
               "T_CM:cm@demo.test" "T_ADMIN:admin@demo.test"; do
  name=${account%%:*}
  want=${account#*:}
  got=$(token_email "${!name}")
  if [ "$got" != "$want" ]; then
    echo "$name authenticates as '${got:-nobody}', not $want." >&2
    echo "Delete $CACHE and re-run to fetch fresh tokens." >&2
    exit 1
  fi
done

# student1's numeric id, resolved rather than assumed. Two assertions below need
# to name "a user who is not the caller", and the obvious shortcut — hardcoding 1,
# since a fresh seed makes student@demo.test the first user — is wrong the moment
# the suite runs anywhere else. Against production, student2 held id 1 and
# student1 held 3, so "another student's progress is not readable" was asking
# student2 to read *their own* progress; the API correctly answered 200 and the
# suite reported a security failure that did not exist.
S1_USER_ID=$(token_user_id "$T_S1")
if [ -z "${S1_USER_ID:-}" ]; then
  echo "Could not read student@demo.test's numeric id from /api/users/me." >&2
  exit 1
fi

# instructor2 registers into the default role; it needs the instructor role for the
# instructor-vs-instructor ownership checks to mean anything. Until role assignment
# moved into the app this was a manual step in Settings -> Users & Permissions ->
# Users, and a run that skipped it passed *vacuously*: every "another instructor
# cannot ..." assertion below expects 403, and a student is 403 too. So the suite
# now assigns the role itself, through the same endpoint the admin dashboard uses,
# and refuses to continue without it.
#
# The numeric ids come from /api/users/me for the same reason S1_USER_ID does — see
# the note above it. The admin's own id is needed for the one assertion that has to
# name the caller: an admin may not change their own role.
I2_USER_ID=$(token_user_id "$T_I2")
ADMIN_USER_ID=$(token_user_id "$T_ADMIN")
if [ -z "${I2_USER_ID:-}" ] || [ -z "${ADMIN_USER_ID:-}" ]; then
  echo "Could not read the numeric ids of instructor2@demo.test / admin@demo.test." >&2
  exit 1
fi

# Read through /api/admin/users rather than /api/users?populate=role: the latter
# needs `find` on the user type *and* on the role type, and the second grant also
# opens /api/users-permissions/roles — every role with its full permission set.
#
# The email is confirmed present before the role is read, because on an empty match
# the first `"type"` in the payload belongs to the assignable-roles list that ships
# alongside the users, and that would report someone else's role as instructor2's.
role_of() {
  local body
  body=$(get "/api/admin/users?q=$1" "$T_ADMIN")
  printf '%s' "$body" | grep -q "\"email\":\"$1\"" || return 0
  printf '%s' "$body" | grep -oP '"type":"\K[^"]+' | head -1
}

I2_ROLE=$(role_of instructor2@demo.test || true)
if [ "${I2_ROLE:-}" != "instructor" ]; then
  echo "  instructor2@demo.test is in '${I2_ROLE:-no role}' — assigning the instructor role."
  status PUT "/api/admin/users/$I2_USER_ID/role" "$T_ADMIN" '{"role":"instructor"}' > /dev/null
  I2_ROLE=$(role_of instructor2@demo.test || true)
fi
if [ "${I2_ROLE:-}" != "instructor" ]; then
  echo "instructor2@demo.test is still not an instructor (found '${I2_ROLE:-no role}')." >&2
  echo "Run 'npm run permissions' in backend/ so the admin role holds" >&2
  echo "api::admin.admin.users and api::admin.admin.setUserRole, then re-run." >&2
  exit 1
fi

# --------------------------------------------------------------------------- #
# Resolve documentIds                                                         #
# --------------------------------------------------------------------------- #
#
# documentIds are random cuid2s regenerated by every fresh seed, so they are
# looked up by natural key rather than hardcoded.
COURSE=$(ids "/api/courses?filters[slug]=$COURSE_SLUG&fields[0]=slug" "$T_ADMIN" | head -1)
[ -n "$COURSE" ] || { echo "Course '$COURSE_SLUG' not found — run 'npm run seed' first."; exit 1; }

readarray -t LESSONS < <(ids \
  "/api/lessons?filters[course][documentId]=$COURSE&fields[0]=title&sort=sequenceOrder:asc&pagination[pageSize]=100" \
  "$T_ADMIN")
# A quiz has no title of its own — which of the two course relations is set is
# what makes it the final quiz or a practice one — so no `fields` here.
FINAL_QUIZ=$(ids "/api/quizzes?filters[course][documentId]=$COURSE" "$T_ADMIN" | head -1)
PRACTICE_QUIZ=$(ids "/api/quizzes?filters[parent_course][documentId]=$COURSE" "$T_ADMIN" | head -1)

# Normalized for the same reason progress is: publishing is one-way, so any
# environment that has ever had this post published stays broken. A production
# database restored from a snapshot taken while it was published fails every
# assertion below, and the post is publicly visible in the meantime.
normalize_draft_blog() {
  local id
  id=$(ids "/api/blogs?filters[slug]=$DRAFT_BLOG_SLUG&fields[0]=slug" "$T_ADMIN" | head -1)
  [ -n "$id" ] || return 0
  status PUT "/api/blogs/$id" "$T_ADMIN" '{"data":{"currentStatus":"draft"}}' > /dev/null
}

normalize_draft_blog

# student2 is the account every "owns nothing" assertion leans on: enrolled nowhere,
# no progress, no results. That is a *precondition*, and nothing established it. This
# suite cleans up after itself, but requesting enrolment as student2 once in the
# browser leaves a row that then survives every run afterwards — and one stray
# approved enrollment turns five assertions into failures that look like leaks and are
# not: an enrolled student may legitimately read the questions of a quiz in their own
# course, so the redaction checks correctly report content reaching them.
#
# Removed loudly rather than silently. Deleting somebody's rows is not something a
# verification script should do without saying so.
normalize_student2() {
  local kind stray
  for kind in enrollments lesson-progresses quiz-results; do
    for stray in $(ids "/api/$kind?pagination[pageSize]=100" "$T_S2"); do
      echo "  removing a stray $kind row left on student2@demo.test ($stray)"
      status DELETE "/api/$kind/$stray" "$T_ADMIN" > /dev/null
    done
  done
}

normalize_student2

PUBLISHED_BLOG=$(ids '/api/blogs?filters[currentStatus]=published&fields[0]=title' "$T_ADMIN" | head -1)
DRAFT_BLOG=$(ids '/api/blogs?filters[currentStatus]=draft&fields[0]=title' "$T_ADMIN" | head -1)

TOTAL_LESSONS=${#LESSONS[@]}
if [ "$TOTAL_LESSONS" -lt 5 ] || [ -z "$FINAL_QUIZ" ] || [ -z "$PRACTICE_QUIZ" ] ||
   [ -z "$PUBLISHED_BLOG" ] || [ -z "$DRAFT_BLOG" ]; then
  # Every value, not a selection of them: the original message printed lessons
  # and the two quizzes only, so a missing blog post — the one thing a restored
  # production database is actually likely to get wrong — showed up as a bail-out
  # with three healthy-looking numbers next to it.
  echo "Seed data incomplete. Run 'npm run seed'."
  echo "  lessons         $TOTAL_LESSONS (want 5 or more)"
  echo "  final quiz      ${FINAL_QUIZ:-MISSING}"
  echo "  practice quiz   ${PRACTICE_QUIZ:-MISSING}"
  echo "  published blog  ${PUBLISHED_BLOG:-MISSING}"
  echo "  draft blog      ${DRAFT_BLOG:-MISSING (is '$DRAFT_BLOG_SLUG' published?)}"
  exit 1
fi

# Three of five complete is the state every assertion below is written against.
normalize_progress() {
  local i
  for i in 0 1 2; do
    post "/api/lessons/${LESSONS[$i]}/complete" "$T_S1" '{}' > /dev/null
  done
  for i in 3 4; do
    post '/api/lesson-progresses' "$T_S1" \
      "{\"data\":{\"lesson\":\"${LESSONS[$i]}\",\"completed\":false}}" > /dev/null
  done
}

normalize_progress

ENROLLMENT=$(ids '/api/enrollments' "$T_S1" | head -1)
S1_PROGRESS=$(ids '/api/lesson-progresses?pagination[pageSize]=100' "$T_S1" | head -1)

# --------------------------------------------------------------------------- #
echo
echo "=== the answer key must never reach the wire ==="
# correctOptionIndex is `private`, so it is stripped from every REST response
# while remaining readable by the Document Service, which is what makes
# server-side grading possible.
for probe in "direct populate:/api/quizzes/$FINAL_QUIZ?populate=Question" \
             "populate=*:/api/quizzes/$FINAL_QUIZ?populate=*" \
             "nested via course:/api/courses/$COURSE?populate[final_quiz][populate]=Question"; do
  label=${probe%%:*}
  url=${probe#*:}
  for who in "student:$T_S1" "admin:$T_ADMIN"; do
    check "$label (${who%%:*})" 0 "$(get "$url" "${who#*:}" | grep -o correctOptionIndex | wc -l)"
  done
done
# The questions must still be readable, or the quiz cannot be taken at all.
check "questions still returned to the student" 4 \
  "$(get "/api/quizzes/$FINAL_QUIZ?populate=Question" "$T_S1" | grep -o '"questionText"' | wc -l)"
check "options still returned to the student" 4 \
  "$(get "/api/quizzes/$FINAL_QUIZ?populate=Question" "$T_S1" | grep -o '"options"' | wc -l)"

# --------------------------------------------------------------------------- #
echo
echo "=== except to whoever may rewrite it ==="
# The one exception to the section above, and the reason the in-app quiz editor can
# exist at all: an author opening a saved quiz has to see which option is marked, or
# every field would render blank and the first save would wipe the key.
#
# So `GET /quizzes/:id/manage` returns it — behind `can-manage-quiz`, the same policy
# that guards the writes, and assembling its payload field by field rather than
# spreading the document, because this is the one place the key leaves the server.
MANAGED=$(get "/api/quizzes/$FINAL_QUIZ/manage" "$T_ADMIN")
check "an admin reads the key back" 4 \
  "$(printf '%s' "$MANAGED" | grep -o correctOptionIndex | wc -l)"
# Not merely that a key came back, but that it is the *same* key the grader uses:
# these are the four answers that score 100 further down.
check "and it is the key grading scores against" 0121 \
  "$(printf '%s' "$MANAGED" | grep -oP '"correctOptionIndex":\K[0-9]+' | tr -d '\n')"
# A quiz has no type column, so the editor titles itself from the relation that is
# set. Getting this wrong would offer a final quiz under a lesson's heading.
check "and it says which kind of quiz this is" '"isFinal":true' \
  "$(printf '%s' "$MANAGED" | grep -o '"isFinal":true')"
check "the course's own instructor reads it too" 4 \
  "$(get "/api/quizzes/$FINAL_QUIZ/manage" "$T_I1" | grep -o correctOptionIndex | wc -l)"
check "and a content manager, who may author anywhere" 4 \
  "$(get "/api/quizzes/$FINAL_QUIZ/manage" "$T_CM" | grep -o correctOptionIndex | wc -l)"
check "an instructor who does not own the course cannot" 403 \
  "$(status GET "/api/quizzes/$FINAL_QUIZ/manage" "$T_I2")"
# The student holds quiz.find and quiz.findOne, so this has to be refused by the
# separate `manage` action rather than by quiz permissions in general.
check "an enrolled student cannot" 403 \
  "$(status GET "/api/quizzes/$FINAL_QUIZ/manage" "$T_S1")"
check "nor an anonymous caller" 403 "$(status GET "/api/quizzes/$FINAL_QUIZ/manage")"

# --------------------------------------------------------------------------- #
echo
echo "=== the inside of a course is what enrolment buys ==="
# A course's *shape* — its lessons' titles, which of them carry a quiz, that a
# final and a practice quiz exist — is the catalog and stays readable. Its
# contents are not: lesson bodies, and above all quiz questions, which are only
# ever meant to be seen while actually taking the quiz.
#
# T_S2 is enrolled in nothing, which is the case that was leaking: `public` holds
# neither lesson.find nor quiz.find, so an anonymous caller never had the relations
# at all, but any signed-in account did.
check "an unenrolled student gets no questions" 0 \
  "$(get "/api/quizzes/$FINAL_QUIZ?populate=Question" "$T_S2" | grep -o '"questionText"' | wc -l)"
check "nor the options they choose between" 0 \
  "$(get "/api/quizzes/$FINAL_QUIZ?populate=Question" "$T_S2" | grep -o '"options"' | wc -l)"
check "nor every quiz on the platform at once" 0 \
  "$(get '/api/quizzes?populate[Question]=true&pagination[pageSize]=100' "$T_S2" | grep -o '"questionText"' | wc -l)"
check "nor a lesson body" 0 \
  "$(get "/api/lessons/${LESSONS[0]}" "$T_S2" | grep -o '"content"' | wc -l)"
check "nor one reached through the course" 0 \
  "$(get "/api/courses/$COURSE?populate[lessons]=true" "$T_S2" | grep -o '"content"' | wc -l)"

# REST populate nests to arbitrary depth, which is why the gate is applied to the
# response and not to the incoming query: a query-shaped guard would have to
# anticipate every one of these separately, and they are not a closed set.
check "nor through a deep populate to the final quiz" 0 \
  "$(get "/api/courses/$COURSE?populate[final_quiz][populate][0]=Question" "$T_S2" | grep -o '"questionText"' | wc -l)"
check "nor through the practice quiz" 0 \
  "$(get "/api/courses/$COURSE?populate[practice_quizzes][populate][0]=Question" "$T_S2" | grep -o '"questionText"' | wc -l)"
check "nor by looping back from a quiz to its course's lessons" 0 \
  "$(get "/api/quizzes/$FINAL_QUIZ?populate[course][populate][0]=lessons" "$T_S2" | grep -o '"content"' | wc -l)"
# The lesson-quiz chain (`course→lessons→quiz→Question`) is asserted in the smoke
# section instead: the seeded course has no lesson quizzes, so the same check here
# would pass with the gate removed entirely.

# The shape genuinely must survive: it is what a student reads to decide whether
# the course is worth requesting.
check "but every lesson still arrives, titled and ordered" "$TOTAL_LESSONS" \
  "$(get "/api/courses/$COURSE?populate[lessons]=true" "$T_S2" | grep -o '"sequenceOrder"' | wc -l)"
check "and the quiz is still listed as existing" 1 \
  "$(rows "/api/quizzes?filters[documentId]=$FINAL_QUIZ" "$T_S2")"

# Over-redaction is the other half of the bug, and the more expensive one: an
# instructor who cannot read their own material cannot check it before publishing,
# and the authoring screens stop working.
check "the course's instructor still reads the questions" 4 \
  "$(get "/api/quizzes/$FINAL_QUIZ?populate=Question" "$T_I1" | grep -o '"questionText"' | wc -l)"
check "and an admin does too" 4 \
  "$(get "/api/quizzes/$FINAL_QUIZ?populate=Question" "$T_ADMIN" | grep -o '"questionText"' | wc -l)"
check "the instructor still reads the lesson body" 1 \
  "$(get "/api/lessons/${LESSONS[0]}" "$T_I1" | grep -o '"content"' | wc -l)"
check "and every body in the course at once" "$TOTAL_LESSONS" \
  "$(get "/api/courses/$COURSE?populate[lessons]=true" "$T_ADMIN" | grep -o '"content"' | wc -l)"
# The twin of the deep-populate checks above: without this they would still pass if
# the chain simply did not resolve, and a guard that is never reached is not a guard.
check "and the deep populate does resolve for them" 4 \
  "$(get "/api/courses/$COURSE?populate[final_quiz][populate][0]=Question" "$T_ADMIN" \
    | grep -o '"questionText"' | wc -l)"
# The enrolled student, who is the whole point: same request, same course, allowed.
check "the enrolled student reads the bodies too" "$TOTAL_LESSONS" \
  "$(get "/api/courses/$COURSE?populate[lessons]=true" "$T_S1" | grep -o '"content"' | wc -l)"

echo
echo "=== progress tracking ==="
P=$(get "/api/courses/$COURSE/progress" "$T_S1")
check "completedLessons" 3 "$(printf '%s' "$P" | num completedLessons)"
check "totalLessons" "$TOTAL_LESSONS" "$(printf '%s' "$P" | num totalLessons)"
check "progressPercent" 60 "$(printf '%s' "$P" | num progressPercent)"

R=$(post "/api/lessons/${LESSONS[0]}/complete" "$T_S1" '{}')
check "re-completing a finished lesson stays 3" 3 "$(printf '%s' "$R" | num completedLessons)"
check "and the percentage does not drift" 60 "$(printf '%s' "$R" | num progressPercent)"

R=$(post "/api/lessons/${LESSONS[3]}/complete" "$T_S1" '{}')
check "completing the 4th lesson -> 4" 4 "$(printf '%s' "$R" | num completedLessons)"
check "completing the 4th lesson -> 80%" 80 "$(printf '%s' "$R" | num progressPercent)"

R=$(post "/api/lessons/${LESSONS[4]}/complete" "$T_S1" '{}')
check "completing the 5th lesson -> 5" 5 "$(printf '%s' "$R" | num completedLessons)"
check "completing the 5th lesson -> 100%" 100 "$(printf '%s' "$R" | num progressPercent)"

check "one progress document per lesson, not per click" 5 \
  "$(rows '/api/lesson-progresses?pagination[pageSize]=100' "$T_S1")"

normalize_progress
check "un-completing returns to 3" 3 \
  "$(get "/api/courses/$COURSE/progress" "$T_S1" | num completedLessons)"

echo
echo "=== server-side grading ==="
R=$(post "/api/quizzes/$FINAL_QUIZ/submit" "$T_S1" '{"answers":[0,1,2,1]}')
check "all correct -> 100" 100 "$(printf '%s' "$R" | num score)"
check "all correct -> 4 of 4" 4 "$(printf '%s' "$R" | num correctCount)"
check "the final quiz is recorded" true "$(printf '%s' "$R" | grep -oP '"recorded":\K(true|false)')"
